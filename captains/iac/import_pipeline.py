"""Clone -> generate -> rewire -> verify -> publish.

Implements docs/iac_import_rewrite_spec.md. The ordering of two stages is
deliberate and worth stating up front:

* **verify runs before publish, always.** A pull request that claims to be safe
  without having been checked is worse than no pull request. When the plan is
  not clean the PR is still opened, but labelled, with the offending plan in the
  body.
* **scrub runs before anything reaches disk.** Generated configuration contains
  whatever AWS returned, and these repositories are often public.

Every stage degrades rather than aborts. Terraform missing, backend
unreachable, index empty — each drops a capability and records why, so the
result is a less polished PR rather than a failed job.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

from captains.iac.normalize import drop_lines, drop_nulls, drop_read_only, invalid_lines
from captains.iac.reference_index import ReferenceIndex, build_reference_index
from captains.iac.repo_checkout import CheckoutError, RepoCheckout
from captains.iac.rewire import RewireResult, rewire
from captains.iac.scrub import scrub
from captains.iac.tf_runner import PlanSummary, TerraformError, TerraformRunner, TerraformUnavailable
from infra_map.models import ResourceNode

logger = logging.getLogger("iac-import-pipeline")

IMPORTS_FILENAME = "beamreach_imports.tf"
RESOURCES_FILENAME = "beamreach_imported.tf"

_SCRATCH_PROVIDER = """# Generated by Beamreach to evaluate imports in isolation.
# No backend is configured: this directory has no state and cannot affect the
# environment it describes.
terraform {{
  required_providers {{
    aws = {{
      source  = "hashicorp/aws"
      version = "{aws_version}"
    }}
  }}
}}

provider "aws" {{
  region = "{region}"
}}
"""


@dataclass
class PipelineResult:
    files: Dict[str, str] = field(default_factory=dict)
    rewired: Optional[RewireResult] = None
    plan: Optional[PlanSummary] = None
    redacted: List[str] = field(default_factory=list)
    normalised: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    generated_by_terraform: bool = False
    verified: bool = False

    @property
    def is_clean(self) -> bool:
        return self.verified and self.plan is not None and self.plan.is_import_only


def _detect_aws_provider_version(checkout_dir: Path) -> str:
    """Match the repository's provider pin where one is discoverable.

    Generated configuration is provider-version-specific: arguments a newer
    provider emits may not exist in the version the repository pins, so the
    resulting PR would not plan for the people who own it.
    """
    lock = checkout_dir / ".terraform.lock.hcl"
    if lock.exists():
        text = lock.read_text(encoding="utf-8", errors="replace")
        marker = 'provider "registry.terraform.io/hashicorp/aws"'
        if marker in text:
            tail = text.split(marker, 1)[1]
            for line in tail.splitlines():
                if "version" in line and "=" in line:
                    return line.split("=", 1)[1].strip().strip('"')
    return ">= 5.0"


class ImportPipeline:
    def __init__(
        self,
        *,
        token: str,
        terraform: Optional[TerraformRunner] = None,
        region: str = "us-east-1",
        target_credentials: Optional[Dict[str, Optional[str]]] = None,
    ):
        self.token = token
        self.region = region

        # Two runners, because the two directories authenticate differently.
        #
        # `tf` runs inside the cloned repository, whose own provider and backend
        # blocks name the profile they expect; it must inherit the ambient
        # environment so those resolve as the repository's authors intended.
        #
        # `tf_target` runs in the scratch directory, whose generated provider
        # block deliberately names no profile — so it needs target-account
        # credentials injected. Without them terraform authenticates as the
        # control-plane account and reports every resource as
        # "Cannot import non-existent remote object", because from there they
        # genuinely do not exist.
        self.tf = terraform or TerraformRunner()
        self.tf_target = (
            TerraformRunner(env=target_credentials, timeout_s=self.tf.timeout_s)
            if target_credentials
            else self.tf
        )

    # --------------------------------------------------------------- stages

    def _generate(
        self,
        scratch: Path,
        import_blocks: str,
        aws_version: str,
        result: PipelineResult,
    ) -> Optional[str]:
        """Stage 4 — terraform writes the resource bodies, in isolation.

        The scratch directory holds only a provider block and the import blocks,
        so there is no backend, no state, and no path by which generation could
        modify the environment being described.
        """
        scratch.mkdir(parents=True, exist_ok=True)
        (scratch / "provider.tf").write_text(
            _SCRATCH_PROVIDER.format(aws_version=aws_version, region=self.region), encoding="utf-8"
        )
        (scratch / IMPORTS_FILENAME).write_text(import_blocks, encoding="utf-8")

        try:
            self.tf_target.init(str(scratch), backend=False)
            generated = self.tf_target.generate_config(str(scratch))
        except (TerraformError, TerraformUnavailable) as exc:
            result.warnings.append(f"config generation unavailable ({exc}); shipping import blocks only")
            return None

        result.generated_by_terraform = True
        return self._normalise(scratch, generated, result)

    def _normalise(self, scratch: Path, generated: str, result: PipelineResult) -> str:
        """Stage 4a — make the generated config something the provider accepts.

        Terraform's generator is faithful to AWS, not to its own schema: it
        emits read-only attributes (`tags_all`) and values the provider refuses
        (`recovery_period_in_days = 0`). Left alone these fail at plan time,
        which is why the verify gate was reporting a dirty plan and the pull
        request was being titled "[needs review]".

        Schema-driven passes handle shape. Value constraints cannot be derived
        from the schema, so terraform is asked directly and the exact lines it
        objects to are removed — general, rather than a hardcoded list of known
        offenders.
        """
        schema: Optional[Dict[str, Any]] = None
        try:
            schema = self.tf_target.providers_schema(str(scratch))
        except (TerraformError, TerraformUnavailable) as exc:
            logger.warning("provider schema unavailable for normalisation: %s", exc)

        text = generated
        if schema:
            read_only = drop_read_only(text, schema)
            text = read_only.text
            if read_only.dropped:
                result.normalised.extend(sorted(set(read_only.dropped)))

        nulls = drop_nulls(text)
        text = nulls.text

        generated_path = scratch / "generated.tf"
        for attempt in range(3):
            generated_path.write_text(text, encoding="utf-8")
            try:
                diagnostics = self.tf_target.validate(str(scratch))
            except (TerraformError, TerraformUnavailable) as exc:
                logger.warning("validate unavailable, shipping unverified config: %s", exc)
                break
            if not diagnostics:
                break
            lines = invalid_lines(diagnostics, "generated.tf")
            if not lines:
                # Errors terraform reports without a line in this file cannot be
                # fixed by deletion; the verify gate will surface them instead.
                result.warnings.append(
                    f"generated config has {len(diagnostics)} unresolved validation error(s)"
                )
                break
            stripped = drop_lines(text, lines)
            text = stripped.text
            result.normalised.extend(stripped.dropped)
            logger.info("attempt %d: removed %d invalid line(s)", attempt + 1, stripped.count)

        if result.normalised:
            logger.info("normalised %d attribute(s) out of the generated config", len(result.normalised))
        return text

    def _scrub(self, scratch: Path, generated: str, public_repo: bool, result: PipelineResult) -> str:
        """Stage 4b — remove sensitive values before anything reaches disk."""
        schema: Optional[Dict[str, Any]] = None
        try:
            schema = self.tf_target.providers_schema(str(scratch))
        except (TerraformError, TerraformUnavailable) as exc:
            logger.warning("provider schema unavailable: %s", exc)

        scrubbed = scrub(generated, schema, require_schema=public_repo)
        result.redacted = scrubbed.redacted
        if scrubbed.redacted:
            result.warnings.append(
                f"{len(scrubbed.redacted)} sensitive value(s) redacted; supply them explicitly before applying"
            )
        return scrubbed.text

    def _init_target(self, target_dir: Path, result: PipelineResult) -> bool:
        """Initialise the checkout once, for both the index and the verify gate.

        This used to live inside `_build_index`, which only runs when generation
        succeeded — so a failed generation left the directory uninitialised and
        the verify plan failed for that reason rather than on its own merits,
        reporting "not verified" when the truth was "never attempted".
        """
        try:
            self.tf.init(str(target_dir), backend=True)
            return True
        except (TerraformError, TerraformUnavailable) as exc:
            result.warnings.append(f"could not initialise {target_dir.name} ({exc})")
            return False

    def _build_index(self, target_dir: Path, addresses: Sequence[str], result: PipelineResult) -> ReferenceIndex:
        """Stage 5 — index the target root module."""
        try:
            return build_reference_index(self.tf, str(target_dir), exclude_addresses=addresses)
        except (TerraformError, TerraformUnavailable) as exc:
            result.warnings.append(f"reference index unavailable ({exc}); values remain literal")
            return ReferenceIndex()

    def _baseline_plan(self, target_dir: Path) -> Optional[PlanSummary]:
        """Plan the checkout before our files are written.

        Establishes what the base branch already intends to change, so the gate
        can judge this pull request on its own contribution rather than on the
        repository's pre-existing drift.
        """
        try:
            return self.tf.plan(str(target_dir))
        except (TerraformError, TerraformUnavailable) as exc:
            logger.warning("baseline plan unavailable, gate will judge against zero: %s", exc)
            return None

    def _verify(
        self,
        target_dir: Path,
        expected: int,
        result: PipelineResult,
        baseline: Optional[PlanSummary] = None,
    ) -> None:
        """Stage 8 — the gate.

        Read-only and unlocked. A dirty plan does not block publication; it
        changes what the pull request says about itself.
        """
        try:
            summary = self.tf.plan(str(target_dir))
        except (TerraformError, TerraformUnavailable) as exc:
            result.warnings.append(f"verification could not run ({exc}); plan was not checked")
            return

        if baseline is not None:
            attributable = summary.minus(baseline)
            if baseline.creates or baseline.updates or baseline.destroys:
                result.warnings.append(
                    f"base branch already plans {len(baseline.creates)} to add, "
                    f"{len(baseline.updates)} to change, {len(baseline.destroys)} to destroy; "
                    "those are pre-existing and not introduced by this PR"
                )
            summary = attributable

        result.plan = summary
        result.verified = True
        if not summary.is_import_only:
            result.warnings.append(
                "plan is not import-only: "
                f"{len(summary.creates)} to add, {len(summary.updates)} to change, "
                f"{len(summary.destroys)} to destroy — review before merging"
            )
        if len(summary.imports) != expected:
            result.warnings.append(
                f"plan reports {len(summary.imports)} import(s) but {expected} were requested"
            )

    # ------------------------------------------------------------------ run

    def run(
        self,
        *,
        repo: str,
        base_branch: str,
        branch: str,
        module_path: str,
        import_blocks: str,
        resources: Sequence[ResourceNode],
        addresses: Sequence[str],
        import_ids: Sequence[str],
        public_repo: bool = True,
        commit_message: str = "beamreach: import unmanaged resources",
    ) -> PipelineResult:
        result = PipelineResult()

        with RepoCheckout(self.token) as repo_checkout:
            checkout = repo_checkout.clone(repo, base_branch)
            target_dir = checkout.root / module_path if module_path else checkout.root
            if not target_dir.is_dir():
                raise CheckoutError(f"module path '{module_path}' does not exist in {repo}")

            aws_version = _detect_aws_provider_version(target_dir)
            scratch = Path(repo_checkout._workdir or "/tmp") / "scratch"

            generated = self._generate(scratch, import_blocks, aws_version, result)

            # Independent of generation: the verify gate needs it too, and a
            # failed generation must not be the reason the plan cannot run.
            initialised = self._init_target(target_dir, result)

            body = ""
            if generated:
                body = self._scrub(scratch, generated, public_repo, result)

                index = self._build_index(target_dir, addresses, result) if initialised else ReferenceIndex()
                if len(index):
                    rewired = rewire(body, index, protected_values=import_ids)
                    result.rewired = rewired
                    body = rewired.text
                    logger.info("rewired %d literal(s) into references", rewired.count)

            files = {f"{module_path}/{IMPORTS_FILENAME}".lstrip("/"): import_blocks}
            if body:
                files[f"{module_path}/{RESOURCES_FILENAME}".lstrip("/")] = body
            result.files = files

            # Baseline before the generated files land: this measures the base
            # branch's own drift, which must not be attributed to the import.
            baseline = self._baseline_plan(target_dir) if initialised else None

            repo_checkout.create_branch(checkout, branch)
            written = repo_checkout.write_files(checkout, files)

            # Verify against the branch as it will be reviewed, with the
            # generated files in place — that is the state a merger inherits.
            if initialised:
                self._verify(target_dir, len(resources), result, baseline=baseline)

            if repo_checkout.commit(checkout, commit_message, written):
                repo_checkout.push(checkout, branch, force=True)
            else:
                result.warnings.append("no changes to commit; branch already matches")

        return result
