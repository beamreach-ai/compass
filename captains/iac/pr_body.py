"""Composes the pull request description.

The body is where the pipeline reports what it did and, more importantly, what
it could not establish. A PR that quietly omits its own uncertainty is the thing
this whole rewrite exists to stop producing: the reviewer has to be able to see
whether the plan was verified, which literals were turned into references and on
what basis, and what was skipped or redacted.
"""

from __future__ import annotations

from typing import Any, List, Sequence, Tuple

from infra_map.models import ResourceNode


def _verification_section(result: Any) -> List[str]:
    if not result.verified:
        return [
            "### Verification",
            "",
            "⚠️ **Not verified.** `terraform plan` could not be run, so this "
            "configuration has not been checked against live infrastructure. "
            "Run a plan before merging.",
            "",
        ]

    plan = result.plan
    if result.is_clean:
        return [
            "### Verification",
            "",
            f"✅ `terraform plan` reports **{len(plan.imports)} import(s) and no other changes** — "
            "applying this brings the resources under Terraform without modifying them.",
            "",
        ]

    lines = [
        "### Verification",
        "",
        "⚠️ **The plan is not import-only.** Applying this would change live "
        "infrastructure beyond the import itself:",
        "",
    ]
    for label, addresses in (
        ("to add", plan.creates),
        ("to change", plan.updates),
        ("to destroy or replace", plan.destroys),
    ):
        if addresses:
            lines.append(f"- **{len(addresses)} {label}:** " + ", ".join(f"`{a}`" for a in addresses[:8]))
    lines.append("")
    return lines


def import_pr_body(
    resources: Sequence[ResourceNode],
    skipped: Sequence[Tuple[ResourceNode, str]],
    result: Any,
) -> str:
    lines: List[str] = [
        "## Terraform Import",
        "",
        f"Brings {len(resources)} unmanaged AWS resource(s) under Terraform control.",
        "",
    ]

    lines += _verification_section(result)

    lines += ["### Resources", ""]
    for node in resources:
        lines.append(f"- `{node.type}/{node.name}` (`{node.resource_id}`)")
    lines.append("")

    if skipped:
        lines += [
            "### Not imported",
            "",
        ]
        for node, why in skipped:
            lines.append(f"- `{node.name}` ({node.type}) — {why}")
        lines.append("")

    if result.rewired and result.rewired.count:
        lines += [
            "### References",
            "",
            f"{result.rewired.count} literal value(s) replaced with references to existing "
            "configuration, so this reads like the rest of the repository rather than a "
            "dump of resource IDs:",
            "",
        ]
        lines += result.rewired.report_lines()
        lines.append("")
        if result.rewired.skipped_identity:
            lines.append(
                "Identity attributes were deliberately left as literals so each block "
                "still matches the resource its import targets."
            )
            lines.append("")

    if result.redacted:
        lines += [
            "### Redacted",
            "",
            f"{len(result.redacted)} sensitive value(s) were removed rather than committed. "
            "Supply them explicitly, or source them from a secret store, before applying:",
            "",
        ]
        lines += [f"- `{item}`" for item in sorted(set(result.redacted))]
        lines.append("")

    if not result.generated_by_terraform:
        lines += [
            "### Limitation",
            "",
            "Terraform was unavailable, so resource bodies were not generated from live "
            "state. Import blocks are included; run "
            "`terraform plan -generate-config-out=generated.tf` to produce the "
            "configuration.",
            "",
        ]

    if result.warnings:
        lines += ["### Notes", ""]
        lines += [f"- {w}" for w in result.warnings]
        lines.append("")

    lines += [
        "### Next steps",
        "",
        "1. Review the generated blocks",
        "2. `terraform plan` to confirm the import",
        "3. `terraform apply` to complete it",
        "4. Delete `beamreach_imports.tf` once applied; keep `beamreach_imported.tf`",
        "",
        "---",
        "*Generated by [Compass](https://github.com/beamreach-ai/compass)*",
    ]
    return "\n".join(lines)
